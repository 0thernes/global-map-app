#!/usr/bin/env python3
"""Validate docs/audit/hardening/findings.csv and write FINDINGS.md from it.

Checks: one label from the fixed set, one category, a known status, a pass id that exists in the pass registry, a fix
commit that exists in git, and a regression test named after every fixed bug. Exit 1 on any violation.
Usage: python3 scripts/audit/hardening_report.py [--check]
"""
import collections
import csv
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / 'docs' / 'audit' / 'hardening'
LABELS = ('bug', 'error', 'issue', 'problem', 'dilemma', 'conflict')
CATEGORIES = ('gap', 'hole', 'blindspot')
STATUSES = ('fixed', 'decided', 'open')
SEVERITIES = ('critical', 'high', 'medium', 'low')
TEST_FILES = ['test/unit/hardening.test.mjs', 'test/py/test_build_data.py', 'test/py/test_hardening_tools.py']


def main():
    rows = list(csv.DictReader(open(OUT / 'findings.csv', encoding='utf-8')))
    registry = open(ROOT / 'scripts' / 'audit' / 'hardening_passes.py', encoding='utf-8').read()
    pass_ids = set(re.findall(r"^    \('([A-Q]\d\d)'", registry, re.M))
    tests = ''.join(open(ROOT / f, encoding='utf-8').read() for f in TEST_FILES).replace('F_', 'F-').replace('_1', '-1').replace('_2', '-2')
    errs, seen = [], set()
    # a shallow CI checkout cannot see older commits: skip that one check there rather than fail spuriously
    shallow = subprocess.run(['git', 'rev-parse', '--is-shallow-repository'], cwd=ROOT, capture_output=True, text=True).stdout.strip() != 'false'
    for r in rows:
        fid = r['id']
        if fid in seen:
            errs.append(f'{fid}: duplicate id')
        seen.add(fid)
        for col, allowed in (('label', LABELS), ('category', CATEGORIES), ('status', STATUSES), ('severity', SEVERITIES)):
            if r[col] not in allowed:
                errs.append(f'{fid}: {col}={r[col]!r} not in {allowed}')
        if r['pass'] not in pass_ids:
            errs.append(f"{fid}: pass {r['pass']} is not in the registry")
        if not fid.startswith(f"F-{r['pass']}-"):
            errs.append(f"{fid}: id does not match pass {r['pass']}")
        if r['fix_commit'] and not shallow and subprocess.run(['git', 'cat-file', '-e', r['fix_commit'] + '^{commit}'], cwd=ROOT, capture_output=True).returncode:
            errs.append(f"{fid}: commit {r['fix_commit']} not found")
        if r['status'] == 'fixed' and r['label'] == 'bug' and not re.search(re.escape(fid) + r'(?![\d])|' + re.escape(fid.rsplit('-', 1)[0]) + r'-\d/\d', tests):
            errs.append(f'{fid}: fixed bug without a regression test named after it')
    if errs:
        print('\n'.join(errs))
        return 1

    by = lambda k: collections.Counter(r[k] for r in rows)
    lab, cat, st, sev = by('label'), by('category'), by('status'), by('severity')
    order = {s: i for i, s in enumerate(SEVERITIES)}
    md = ['# Hardening findings (v1.5.1)', '',
          'Generated by `scripts/audit/hardening_report.py` from [findings.csv](findings.csv); do not edit by hand.',
          'Passes and how they were run: [PASSES.md](PASSES.md). Repository index: [INDEX.md](INDEX.md).', '',
          f'**{len(rows)} findings.** ' + ' · '.join(f'{k} {lab[k]}' for k in LABELS if lab[k]) + '.', '',
          '| | ' + ' | '.join(STATUSES) + ' | total |', '| --- |' + ' --- |' * (len(STATUSES) + 1)]
    for lb in LABELS:
        if lab[lb]:
            c = collections.Counter(r['status'] for r in rows if r['label'] == lb)
            md.append(f'| {lb} | ' + ' | '.join(str(c[s]) for s in STATUSES) + f' | {lab[lb]} |')
    md.append('| **total** | ' + ' | '.join(str(st[s]) for s in STATUSES) + f' | {len(rows)} |')
    md += ['', 'Categories: ' + ' · '.join(f'{k} {cat[k]}' for k in CATEGORIES) + '. Severity: ' +
           ' · '.join(f'{k} {sev[k]}' for k in SEVERITIES if sev[k]) + '.', '',
           '| ID | Pass | Where | Label | Category | Severity | Evidence | Fix or decision | Commit | Status |',
           '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |']
    for r in sorted(rows, key=lambda r: (order[r['severity']], r['id'])):
        cell = lambda s: s.replace('|', '\\|')
        md.append(f"| {r['id']} | {r['pass']} | `{cell(r['file_line'])}` | {r['label']} | {r['category']} | {r['severity']} | "
                  f"{cell(r['evidence'])} | {cell(r['fix'])} | {r['fix_commit']} | {r['status']} |")
    text = '\n'.join(md) + '\n'
    if '--check' in sys.argv:  # validate only; fail if FINDINGS.md is stale
        if (OUT / 'FINDINGS.md').read_text(encoding='utf-8') != text:
            print('FINDINGS.md is stale: run python3 scripts/audit/hardening_report.py')
            return 1
        return 0
    (OUT / 'FINDINGS.md').write_text(text, encoding='utf-8')
    print(f"{len(rows)} findings: {dict(lab)}; status {dict(st)}")
    return 0


if __name__ == '__main__':
    sys.exit(main())
