#!/usr/bin/env python3
"""Reproducible table of contents of every tracked file.

Writes docs/audit/hardening/INDEX.md (and index.csv): one row per `git ls-files`
entry with path, line count (text) or byte size (binary), role and owner module.
Run: python3 scripts/audit/index_repo.py
Deterministic: output depends only on the tracked tree (sorted paths, no timestamps).
"""
import csv
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs/audit/hardening"

# (prefix, role, owner module). First match wins, so specific prefixes go first.
RULES = [
    (".github/workflows/", "CI/CD workflow", "ci"),
    (".github/", "GitHub community/config", "repo"),
    ("src/cesium/", "Globe renderer module (Cesium)", "globe"),
    ("src/ui/", "Console UI component", "ui-shell"),
    ("src/ui_", "Panel UI module", "ui-panels"),
    ("src/globe_cesium.js", "Globe renderer entry", "globe"),
    ("src/labels_cesium.js", "Globe labels", "globe"),
    ("src/app", "App bootstrap/state", "core"),
    ("src/", "Domain/analysis module", "core"),
    ("js/", "Built bundle (generated by scripts/build.mjs)", "build-output"),
    ("css/", "Stylesheet", "ui-shell"),
    ("index.html", "App entry HTML (CSP, layout skeleton)", "ui-shell"),
    ("test/unit/", "Unit test (node:test)", "tests"),
    ("test/", "Browser/e2e test harness (Playwright)", "tests"),
    ("scripts/audit/", "Audit tooling", "audit"),
    ("scripts/design/", "Design/wireframe generator", "design"),
    ("scripts/", "Build/validation tooling", "build"),
    ("data/tools/", "Data pipeline tool", "data-pipeline"),
    ("data/sources/", "Source snapshot (provenance input)", "data-sources"),
    ("data/layers/", "Generated layer data", "data-layers"),
    ("data/briefings/", "Briefing material", "data-briefings"),
    ("data/", "Data file", "data"),
    ("docs/audit/hardening/", "Hardening audit record", "audit"),
    ("docs/audit/", "Audit record", "audit"),
    ("docs/adr/", "Architecture decision record", "docs"),
    ("docs/screenshots/", "Screenshot evidence", "docs-media"),
    ("docs/wireframes/", "Wireframe image", "design"),
    ("docs/design/", "Design documentation", "design"),
    ("docs/", "Documentation", "docs"),
    ("vendor/cesium/", "Vendored CesiumJS build (third party)", "vendor"),
    ("vendor/three/", "Vendored three.js (third party)", "vendor"),
    ("vendor/", "Vendored asset (third party)", "vendor"),
    ("textures/", "Earth texture (base64 JS module)", "assets"),
    ("assets/audio/", "Audio asset", "assets"),
    ("assets/", "Static asset", "assets"),
    ("shots/", "Screenshot scratch output", "docs-media"),
    ("RELEASE_NOTES_", "Release notes", "docs"),
]
TOP = {
    "README.md": "Project overview + repo checklist",
    "CHANGELOG.md": "Change history (Keep a Changelog)",
    "CITATION.cff": "Citation metadata",
    "LICENSE": "Code licence (MIT)",
    "DATA_LICENSE.md": "Data licensing/attribution",
    "CREDITS.md": "Third-party credits",
    "SECURITY.md": "Security policy",
    "SUPPORT.md": "Support policy",
    "CONTRIBUTING.md": "Contribution guide",
    "CODE_OF_CONDUCT.md": "Code of conduct",
    "package.json": "npm manifest",
    "package-lock.json": "npm lockfile",
    "eslint.config.js": "Lint config",
    "build.sh": "Convenience build script",
    "launch.cmd": "Windows launcher",
}
BINARY_EXT = {".png", ".jpg", ".jpeg", ".gif", ".webp", ".mp3", ".wasm", ".gz", ".woff", ".woff2", ".ico", ".pdf", ".ktx2", ".glb", ".bin"}


def classify(p: str):
    if p in TOP:
        return TOP[p], "repo"
    for prefix, role, owner in RULES:
        if p.startswith(prefix):
            return role, owner
    if p.startswith("."):
        return "Tool config", "repo"
    return "Other", "repo"


def measure(path: Path):
    data = path.read_bytes()
    if path.suffix.lower() in BINARY_EXT or b"\0" in data[:8192]:
        return None, len(data)
    return data.count(b"\n") + (0 if data.endswith(b"\n") or not data else 1), len(data)


def main():
    files = subprocess.run(["git", "ls-files", "-z"], cwd=ROOT, capture_output=True, check=True).stdout.decode().split("\0")
    files = sorted(f for f in files if f)
    rows = []
    for f in files:
        p = ROOT / f
        if not p.exists():
            continue
        lines, size = measure(p)
        role, owner = classify(f)
        rows.append((f, lines, size, role, owner))
    OUT.mkdir(parents=True, exist_ok=True)
    with open(OUT / "index.csv", "w", newline="") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(["n", "path", "lines", "bytes", "role", "owner"])
        for i, r in enumerate(rows, 1):
            w.writerow([i, r[0], "" if r[1] is None else r[1], r[2], r[3], r[4]])
    # table of contents grouped by owner module
    by_owner = {}
    for r in rows:
        by_owner.setdefault(r[4], []).append(r)
    total_lines = sum(r[1] or 0 for r in rows)
    out = [
        "# Repository index (table of contents)",
        "",
        "Generated by `python3 scripts/audit/index_repo.py` from `git ls-files`. Do not edit by hand.",
        f"Machine-readable copy: [index.csv](index.csv). {len(rows)} tracked files, {total_lines:,} text lines.",
        "",
        "## Contents",
        "",
        "| # | Owner module | Files | Text lines | Bytes |",
        "|---|---|---:|---:|---:|",
    ]
    owners = sorted(by_owner)
    for i, o in enumerate(owners, 1):
        rs = by_owner[o]
        out.append(f"| {i} | [{o}](#{i}-{o}) | {len(rs)} | {sum(r[1] or 0 for r in rs):,} | {sum(r[2] for r in rs):,} |")
    n = 0
    num = {r[0]: k for k, r in enumerate(rows, 1)}
    for i, o in enumerate(owners, 1):
        out += ["", f"## {i}. {o}", "", "| # | Path | Lines | Bytes | Role |", "|---:|---|---:|---:|---|"]
        for r in by_owner[o]:
            n += 1
            lines = "binary" if r[1] is None else f"{r[1]:,}"
            out.append(f"| {num[r[0]]} | `{r[0]}` | {lines} | {r[2]:,} | {r[3]} |")
    (OUT / "INDEX.md").write_text("\n".join(out) + "\n")
    print(f"indexed {len(rows)} files, {total_lines} text lines, {len(owners)} owner modules")


if __name__ == "__main__":
    sys.exit(main())
