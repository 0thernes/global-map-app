"""Write docs/layer-catalog.md from the generated data files (title, rows, size, source string of every layer).
Usage: python3 scripts/layer_catalog.py"""
import glob, json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def payload(p):
    t = open(p, encoding='utf-8').read()
    if not t.startswith('GM.reg'): return None
    return json.loads(t[t.index(',') + 1:t.rindex(')')])

def count(j):
    for k in ('items', 'events', 'features', 'lines', 'rows'):
        if isinstance(j.get(k), list): return len(j[k])
    if isinstance(j.get('cols'), dict): return len(next(iter(j['cols'].values()), []))
    return ''

out = ['# Layer catalog', '', 'Generated by `python3 scripts/layer_catalog.py` from `data/layers/*.js`. Rows = records in the file '
       '(blank for line, polygon and raster layers). Licences: [CREDITS.md](../CREDITS.md) and [DATA_LICENSE.md](../DATA_LICENSE.md).', '',
       '| File | Title | Rows | Size | Source |', '|---|---|---:|---:|---|']
for p in sorted(glob.glob(os.path.join(ROOT, 'data', 'layers', '*.js'))):
    j = payload(p)
    if j is None: continue
    src = str(j.get('source') or j.get('attribution') or '').replace('|', '/').replace('\n', ' ')
    out.append('| `%s` | %s | %s | %.1f MB | %s |' % (os.path.basename(p), j.get('title', ''), count(j), os.path.getsize(p) / 1e6, src[:400]))
s = open(os.path.join(ROOT, 'data', 'cases.js'), encoding='utf-8').read(); i = s.index('window.GM_CASES=') + 16
rows, _ = json.JSONDecoder().raw_decode(s[i:])
out += ['', '## Cases (`data/cases.js`)', '', '%d public case rows (NUFORC rows are local-only, see DATA_LICENSE.md).' % len(rows), '']
from collections import Counter
out += ['| Category | Rows |', '|---|---:|'] + ['| %s | %d |' % kv for kv in Counter(r.get('category') for r in rows).most_common()]
out += ['', 'Lazy tiles: `data/layers/hydrolakes_tiles/` (HydroLAKES 1–10 km² by 10° tile) and `data/layers/postal/` (GeoNames postal codes by country).']
open(os.path.join(ROOT, 'docs', 'layer-catalog.md'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('wrote docs/layer-catalog.md', len(out))
